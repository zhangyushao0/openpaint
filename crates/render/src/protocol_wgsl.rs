//! The protocol's WGSL side: the declarations `prelude` generates from the Rust definitions in
//! `protocol.rs` (constants, opcodes, slots, record structs).

use std::mem::{offset_of, size_of};

use super::adjust::{ADJUST_KINDS, ADJUST_ONS, ADJUST_SLOTS};
use super::layers::{INTOS, LAYER_SLOTS, MASKINGS, MODES};
use super::moves::MOVE_SLOTS;
use super::{
    BLENDS, FRESH, GRAIN_ONE, MASK_HEADER, MOVE_DEPTH, Op, Opcode, Params, SLOTS, TILE, TIPS,
    TileRecord,
};
use crate::paper::{MOMENT_ONE, PAPER_SIZE, level_count};
use crate::smudge::{NODE_WORDS, RESIDUAL_HEADER, RESIDUAL_TILE, TILE_NODES};

/// A WGSL struct generated from a Rust record: name, size and `(field, WGSL type, offset)`.
pub(super) struct Layout {
    pub(super) name: &'static str,
    pub(super) size: usize,
    pub(super) fields: &'static [(&'static str, &'static str, usize)],
}

pub(super) const LAYOUTS: [Layout; 3] = [
    Layout {
        name: "Op",
        size: size_of::<Op>(),
        fields: &[
            ("code", "u32", offset_of!(Op, code)),
            ("data", "array<f32, 14>", offset_of!(Op, data)),
        ],
    },
    Layout {
        name: "Tile",
        size: size_of::<TileRecord>(),
        fields: &[
            ("origin", "vec2<u32>", offset_of!(TileRecord, origin)),
            ("output", "vec2<u32>", offset_of!(TileRecord, output)),
            ("start", "u32", offset_of!(TileRecord, start)),
            ("count", "u32", offset_of!(TileRecord, count)),
        ],
    },
    Layout {
        name: "Params",
        size: size_of::<Params>(),
        fields: &[
            ("background", "vec4<f32>", offset_of!(Params, background)),
            ("tiles", "u32", offset_of!(Params, tiles)),
            ("row", "u32", offset_of!(Params, row)),
            ("size", "vec2<u32>", offset_of!(Params, size)),
            ("kept", "u32", offset_of!(Params, kept)),
            ("level", "f32", offset_of!(Params, level)),
            ("scale", "f32", offset_of!(Params, scale)),
            ("inverse", "f32", offset_of!(Params, inverse)),
            ("base_x", "vec4<f32>", offset_of!(Params, base_x)),
            ("base_y", "vec4<f32>", offset_of!(Params, base_y)),
        ],
    },
];

/// WGSL declarations of the protocol: the tile size, the paper's dimensions, one constant per
/// opcode, named operand slot, blend and tip, one struct per record.
pub(crate) fn prelude() -> String {
    let mut wgsl = String::from("// Generated by crates/render/src/protocol.rs.\n");
    wgsl.push_str(&format!("const TILE: u32 = {TILE}u;\n"));
    wgsl.push_str(&format!("const FRESH: u32 = {FRESH}u;\n"));
    wgsl.push_str(&format!("const GRAIN_ONE: u32 = {GRAIN_ONE}u;\n"));
    wgsl.push_str(&format!("const MASK_HEADER: u32 = {MASK_HEADER}u;\n"));
    wgsl.push_str(&format!("const MOVE_DEPTH: u32 = {MOVE_DEPTH}u;\n"));
    let [width, height] = PAPER_SIZE;
    wgsl.push_str(&format!("const PAPER_WIDTH: u32 = {width}u;\n"));
    wgsl.push_str(&format!("const PAPER_HEIGHT: u32 = {height}u;\n"));
    wgsl.push_str(&format!("const PAPER_LEVELS: u32 = {}u;\n", level_count()));
    wgsl.push_str(&format!("const MOMENT_ONE: u32 = {MOMENT_ONE}u;\n"));
    for (name, value) in [
        ("RESIDUAL_TILE", RESIDUAL_TILE),
        ("TILE_NODES", TILE_NODES),
        ("NODE_WORDS", NODE_WORDS),
        ("RESIDUAL_HEADER", RESIDUAL_HEADER),
    ] {
        wgsl.push_str(&format!("const {name}: u32 = {value}u;\n"));
    }
    named_values(&mut wgsl);
    for (name, blend) in BLENDS {
        wgsl.push_str(&format!("const {name}: u32 = {}u;\n", blend as u32));
    }
    for (name, mode) in MODES {
        wgsl.push_str(&format!("const {name}: u32 = {}u;\n", mode as u32));
    }
    for (name, into) in INTOS {
        wgsl.push_str(&format!("const {name}: u32 = {}u;\n", into as u32));
    }
    for (name, masking) in MASKINGS {
        wgsl.push_str(&format!("const {name}: u32 = {}u;\n", masking as u32));
    }
    for (name, tip) in TIPS {
        wgsl.push_str(&format!("const {name}: u32 = {}u;\n", tip as u32));
    }
    for opcode in Opcode::ALL {
        wgsl.push_str(&format!(
            "const {}: u32 = {}u;\n",
            opcode.wgsl_name(),
            opcode as u32
        ));
    }
    for layout in &LAYOUTS {
        wgsl.push_str(&format!(
            "// {} bytes, as in Rust.\nstruct {} {{\n",
            layout.size, layout.name
        ));
        for (field, ty, _) in layout.fields {
            wgsl.push_str(&format!("    {field}: {ty},\n"));
        }
        wgsl.push_str("}\n");
    }
    wgsl
}

/// The named operand slots, and the adjustments' kinds and targets.
fn named_values(wgsl: &mut String) {
    for (name, slot) in SLOTS
        .into_iter()
        .chain(LAYER_SLOTS)
        .chain(ADJUST_SLOTS)
        .chain(MOVE_SLOTS)
    {
        wgsl.push_str(&format!("const {name}: u32 = {slot}u;\n"));
    }
    for (name, kind) in ADJUST_KINDS {
        wgsl.push_str(&format!("const {name}: u32 = {}u;\n", kind as u32));
    }
    for (name, on) in ADJUST_ONS {
        wgsl.push_str(&format!("const {name}: u32 = {}u;\n", on as u32));
    }
}
